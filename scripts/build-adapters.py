#!/usr/bin/env python3
"""Generate the tool adapters from a single source (`adapters/source/harness.md`).

Usage:
  build-adapters.py          rewrites adapters/*
  build-adapters.py --check  fails (exit 1) if any adapter is out of sync

Adapters are optional pointers: the harness does not depend on any tool.
"""
from __future__ import annotations

import sys
from pathlib import Path

KIT = Path(__file__).resolve().parents[1]
SOURCE = KIT / "adapters/source/harness.md"
NOTICE = "<!-- Generated by scripts/build-adapters.py from adapters/source/harness.md — do not edit by hand. -->"

# id → (file in the kit, frontmatter, title)
ADAPTERS: dict[str, tuple[str, str, str]] = {
    "agents-md": ("adapters/agents-md/agents.md", "", "# AGENTS — AI Engineering Harness"),
    "claude": ("adapters/claude-code/claude.md", "", "# CLAUDE — AI Engineering Harness"),
    "copilot": ("adapters/github-copilot/copilot-instructions.md", "", "# Copilot — AI Engineering Harness"),
    "cursor": (
        "adapters/cursor/rules/harness-sdd.mdc",
        "---\ndescription: AI Engineering Harness — entrypoint .ai-harness/agents.md\nalwaysApply: true\n---\n",
        "# AI Engineering Harness",
    ),
    "windsurf": ("adapters/windsurf/.windsurfrules", "", "# Windsurf — AI Engineering Harness"),
    "continue": (
        "adapters/continue/rules/harness-sdd.md",
        '---\nname: AI Engineering Harness\ndescription: Entrypoint .ai-harness/agents.md\nglobs:\n  - "**/*"\n---\n',
        "# AI Engineering Harness",
    ),
    "aider": ("adapters/aider/conventions.md", "", "# CONVENTIONS — AI Engineering Harness"),
    "jetbrains": ("adapters/jetbrains/rules/harness.md", "", "# AI Engineering Harness — JetBrains AI"),
}


def render(frontmatter: str, title: str, body: str) -> str:
    parts = [frontmatter] if frontmatter else []
    parts.append(f"{NOTICE}\n\n{title}\n\n{body.strip()}\n")
    return "\n".join(parts) if frontmatter else parts[0]


def main(argv: list[str]) -> int:
    check = "--check" in argv
    body = SOURCE.read_text(encoding="utf-8")
    stale = []
    for rel, frontmatter, title in ADAPTERS.values():
        path = KIT / rel
        content = render(frontmatter, title, body)
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        if check:
            stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"generated: {rel}")
    if stale:
        print("adapters out of sync (run scripts/build-adapters.py):")
        for rel in stale:
            print(f"  {rel}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
